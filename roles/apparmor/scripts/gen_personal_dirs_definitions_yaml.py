#!/usr/bin/env python3
"""Generate a YAML scaffold of personal-directory access definitions.

Output is consumed by roles/apparmor/scripts/gen_personal_dirs_aa_mixins.py at playbook
run time to produce the per-category AppArmor abstractions
    /etc/apparmor.d/abstractions/local_mixin_personal_dirs__for__<category>

Every scaffolded entry starts with `allow: []` (no app may access). Edit the
file to open specific directories to specific app categories. See
roles/apparmor/app_categories.yml for the category list.

Usage examples:
  python3 roles/apparmor/scripts/gen_personal_dirs_definitions_yaml.py ~/secrets ~/Personal/Projects/*
  python3 roles/apparmor/scripts/gen_personal_dirs_definitions_yaml.py ~/vault/* -o /tmp/personal_dirs.yml
"""

import argparse
import glob
import os
import sys
from pathlib import Path

# Reuse the schema builder + writer from the abstraction generator so the
# scaffold and the playbook-time builder cannot disagree on schema shape.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_personal_dirs_aa_mixins import load_categories, schema_path_for, write_schema  # noqa: E402

# `roles/apparmor/scripts/<this file>` -> `roles/apparmor/` is two `parent`s up.
_ROLE_DIR = Path(__file__).resolve().parent.parent
_DEFAULT_OUTPUT = _ROLE_DIR / "local_vars" / "personal_dirs.yml"
_DEFAULT_CATEGORIES_FILE = _ROLE_DIR / "app_categories.yml"


def resolve_paths(raw: str) -> list[Path]:
    """Expand ~ and glob in a path argument, return only existing directories."""
    expanded = os.path.expanduser(raw)
    matches = glob.glob(expanded)
    if not matches:
        return []
    return [Path(m) for m in matches if Path(m).is_dir()]


def _quote(p: str) -> str:
    """Return a YAML-safe double-quoted path. The only escaping needed for
    typical filesystem paths is the backslash and the double quote itself."""
    return '"' + p.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build_yaml(dirs: list[Path], schema_basename: str) -> str:
    """Render the scaffold YAML body. Paths are always double-quoted so spaces
    and other YAML-special characters are unambiguous.

    The first line is a `yaml-language-server` directive pointing at the
    companion JSON Schema, so editors with the Red Hat YAML extension (or
    coc-yaml, lsp-mode etc.) load it automatically and validate inline."""
    lines: list[str] = [
        f"# yaml-language-server: $schema=./{schema_basename}",
        "# Generated by roles/apparmor/scripts/gen_personal_dirs_definitions_yaml.py",
        "# Edit the `allow` lists, then run the playbook. Schema is validated",
        "# at playbook run time by roles/apparmor/scripts/gen_personal_dirs_aa_mixins.py.",
        "#",
        "# `allow` values:",
        "#   []            no app may access (audit deny in every abstraction)",
        '#   ["*"]         every abstraction allows (must appear alone)',
        "#   [pdf_viewer]  only the pdf_viewer abstraction allows",
        "#   [pdf_viewer, image_viewer]   both abstractions allow",
        "#",
        "# Categories: see roles/apparmor/app_categories.yml",
        "",
    ]
    for d in sorted(dirs, key=str):
        p = str(d).rstrip("/")
        lines.append(f"- path: {_quote(p)}")
        lines.append("  allow: []")
    return "\n".join(lines) + "\n"


def main() -> None:
    if len(sys.argv) == 1:
        print(__doc__)
        sys.exit(1)

    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "paths",
        nargs="+",
        metavar="PATH_OR_GLOB",
        help=(
            "Directory path or shell glob. "
            "~ is expanded. "
            "Globs are resolved; only directories are kept. "
            "Example: ~/secrets ~/Personal/Projects/*"
        ),
    )
    parser.add_argument(
        "-o",
        "--output",
        metavar="FILE",
        default=_DEFAULT_OUTPUT,
        help=f"Output file (default: {_DEFAULT_OUTPUT}). Created if absent.",
    )
    parser.add_argument(
        "--categories",
        metavar="FILE",
        type=Path,
        default=_DEFAULT_CATEGORIES_FILE,
        help=(
            f"Categories YAML used to write the companion JSON Schema "
            f"(default: {_DEFAULT_CATEGORIES_FILE})."
        ),
    )
    args = parser.parse_args()

    resolved: list[Path] = []
    for raw in args.paths:
        found = resolve_paths(raw)
        if not found:
            print(f"error: no directories matched: {raw!r}", file=sys.stderr)
            sys.exit(1)
        resolved.extend(found)

    # Deduplicate while preserving sort order.
    seen: set[Path] = set()
    unique: list[Path] = []
    for p in resolved:
        if p not in seen:
            seen.add(p)
            unique.append(p)

    if not unique:
        print("error: no valid directories found - nothing written.", file=sys.stderr)
        sys.exit(1)

    output_path = Path(args.output).expanduser()
    output_path.parent.mkdir(parents=True, exist_ok=True)

    schema_path = schema_path_for(output_path)
    body = build_yaml(unique, schema_path.name)
    output_path.write_text(body, encoding="utf-8")

    # Write the companion schema upfront so editors get autocomplete on first
    # open, before the playbook has ever run. Builder rewrites it on every
    # ansible run to keep it in sync with app_categories.yml.
    try:
        categories = load_categories(args.categories)
    except (OSError, ValueError) as e:
        print(f"error loading {args.categories}: {e}", file=sys.stderr)
        sys.exit(1)
    write_schema(output_path, categories)

    n = len(unique)
    print(f"Scaffolded {n} director{'y' if n == 1 else 'ies'}:")
    for p in unique:
        print(f"  {p}")
    print(f"\nOutput file:\n  {output_path.resolve()}")
    print(f"Companion schema: {schema_path.resolve()}")
    print(
        "\nNext: edit the `allow` lists to grant access to specific categories,\n"
        "then run the playbook. Categories: see roles/apparmor/app_categories.yml."
    )


if __name__ == "__main__":
    main()
